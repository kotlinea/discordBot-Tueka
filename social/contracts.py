from typing import Any, Protocol


class SocialMessagePort(Protocol):
    def available(self, guild_id: int, channel_id: int) -> bool: ...
    async def send(self, guild_id: int, channel_id: int, content: str, embed: dict[str, Any], role_id: int | None,
                   receipt_key: str, *, recover: bool, created_at: int) -> int: ...
    async def edit(self, guild_id: int, channel_id: int, message_id: int, embed: dict[str, Any]) -> None: ...
