"""Export the real router's OpenAPI and deterministic TypeScript contracts.

Uses an isolated temporary database and no OAuth, Discord, or network access.
Run with --check in CI to reject stale checked-in generated artifacts.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from fastapi import FastAPI
from dashboard.api_v1 import create_api_router
from migrate import apply


def identifier(value: str) -> str:
    return re.sub(r'\W', '_', value)


def typescript(schema: dict) -> str:
    if '$ref' in schema:
        return identifier(schema['$ref'].rsplit('/', 1)[-1])
    if 'const' in schema:
        return json.dumps(schema['const'], ensure_ascii=False)
    if 'enum' in schema:
        return ' | '.join(json.dumps(value, ensure_ascii=False) for value in schema['enum'])
    for key, separator in (('anyOf', ' | '), ('oneOf', ' | '), ('allOf', ' & ')):
        if key in schema:
            return '(' + separator.join(typescript(value) for value in schema[key]) + ')'
    kind = schema.get('type')
    if kind == 'array':
        return 'Array<' + typescript(schema.get('items', {})) + '>'
    if kind == 'object' or 'properties' in schema:
        properties = schema.get('properties', {})
        if not properties:
            extra = schema.get('additionalProperties', {})
            return 'Record<string, ' + (typescript(extra) if isinstance(extra, dict) else 'unknown') + '>'
        required = schema.get('required', [])
        return '{ ' + '; '.join(json.dumps(key) + ('' if key in required else '?') + ': ' + typescript(value)
                                for key, value in properties.items()) + ' }'
    return {'string': 'string', 'integer': 'number', 'number': 'number', 'boolean': 'boolean', 'null': 'null'}.get(kind, 'unknown')


def artifacts() -> dict[Path, str]:
    with tempfile.TemporaryDirectory(prefix='tueka-openapi-') as directory:
        base = Path(directory)
        database = base / 'schema.sqlite3'
        apply(database, base / 'backups')
        app = FastAPI(title='Tueka Dashboard API', version='1.0.0')
        app.include_router(create_api_router(database, object()))
        document = app.openapi()
    schemas = document.get('components', {}).get('schemas', {})
    lines = ['// Generated by scripts/generate_api.py. Do not edit.', '']
    for name, schema in sorted(schemas.items()):
        lines.append(f'export type {identifier(name)} = {typescript(schema)}')
    limits = {name: {field: {key: value for key, value in spec.items() if key in {'minLength', 'maxLength', 'minimum', 'maximum', 'minItems', 'maxItems', 'pattern'}} for field, spec in schema.get('properties', {}).items()} for name, schema in schemas.items()}
    lines += ['', 'export const constraints = ' + json.dumps(limits, ensure_ascii=False, sort_keys=True, indent=2) + ' as const']
    lines += ['', "export type Locale = Preferences['locale']", "export type Appearance = Preferences['appearance']",
              "export type ColorScheme = Preferences['color_scheme']",
              "export type ReactionRoleBehavior = ReactionRoleMessage['behavior_type']", '', 'export interface Operations {']
    for path, operations in sorted(document['paths'].items()):
        for method, operation in sorted(operations.items()):
            if method not in {'get', 'post', 'put', 'patch', 'delete'}:
                continue
            success = next(value for key, value in operation['responses'].items() if key.startswith('2'))
            media = success.get('content', {}).get('application/json')
            result = typescript(media['schema']) if media else ('Blob' if 'application/octet-stream' in success.get('content', {}) else 'void')
            request = operation.get('requestBody', {}).get('content', {}).get('application/json', {}).get('schema')
            body = typescript(request) if request else 'never'
            lines.append(f'  {json.dumps(method.upper() + " " + path)}: {{ response: {result}; body: {body} }}')
    lines += ['}', '']
    return {
        ROOT / 'dashboard' / 'api' / 'openapi.json': json.dumps(document, ensure_ascii=False, indent=2, sort_keys=True) + '\n',
        ROOT / 'dashboard' / 'frontend' / 'src' / 'generated' / 'api.ts': '\n'.join(lines),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    options = parser.parse_args()
    stale = []
    for path, content in artifacts().items():
        if options.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8')
    if stale:
        print('Stale generated API artifacts: ' + ', '.join(stale), file=sys.stderr)
        return 1
    print('API artifacts are current.' if options.check else 'Generated OpenAPI and TypeScript contracts.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
