from dataclasses import dataclass
from typing import Protocol


@dataclass(frozen=True)
class ContainerRef:
    id: int
    parent_id: int | None


class TicketResourcePort(Protocol):
    async def create_container(self, ticket: dict, panel: dict, name: str, team_roles: list[int], on_call: list[int]) -> ContainerRef: ...
    async def recover_container(self, ticket: dict, panel: dict, resource_id: int) -> ContainerRef: ...
    async def claim_changes(self, ticket: dict, panel: dict, member_id: int | None, team_roles: list[int]) -> list[dict]: ...
    async def permission(self, ticket: dict, change: dict, *, restore: bool = False) -> None: ...

    async def participant(self, ticket: dict, user_id: int, *, add: bool) -> None: ...
    async def notes_thread(self, ticket: dict, *, recover: bool) -> int: ...
    async def send_reply(self, ticket: dict, delivery_key: str, content: str, *, recover: bool) -> dict: ...
    async def category(self, ticket: dict) -> int | None: ...
    async def move_category(self, ticket: dict, target: int | None, *, expected: int | None) -> None: ...
    async def find_container(self, ticket: dict, panel: dict) -> ContainerRef: ...
    async def member_identity(self, ticket: dict) -> dict: ...
    async def notice(self, ticket: dict, key: str, packet: dict, *, recover: bool) -> dict: ...
    async def remove_open_mentions(self, ticket: dict, message_id: int) -> None: ...
    async def delete_resource(self, ticket: dict) -> None: ...
