CREATE TABLE appeal_threads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    interaction_id BIGINT NOT NULL UNIQUE,
    kind TEXT NOT NULL CHECK(kind IN ('appeal','modmail')),
    case_id BIGINT,
    original_moderator_id BIGINT,
    case_action TEXT,
    application_id BIGINT,
    ticket_id BIGINT,
    status TEXT NOT NULL DEFAULT 'open' CHECK(status IN ('open','reviewing','accepted','rejected','closed','withdrawn')),
    revision INTEGER NOT NULL DEFAULT 1,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX appeal_threads_open ON appeal_threads(guild_id,author_id,COALESCE(case_id,0)) WHERE status IN ('open','reviewing');
CREATE INDEX appeal_threads_guild ON appeal_threads(guild_id,id);
CREATE INDEX appeal_threads_expiry ON appeal_threads(expires_at);
CREATE TABLE appeal_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_id BIGINT NOT NULL REFERENCES appeal_threads(id) ON DELETE CASCADE,
    actor_id BIGINT NOT NULL,
    staff INTEGER NOT NULL CHECK(staff IN (0,1)),
    content TEXT NOT NULL,
    interaction_id BIGINT UNIQUE,
    created_at BIGINT NOT NULL
);
CREATE TABLE appeal_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_id BIGINT NOT NULL REFERENCES appeal_threads(id) ON DELETE CASCADE,
    actor_id BIGINT NOT NULL,
    event_type TEXT NOT NULL,
    reason TEXT NOT NULL DEFAULT '',
    created_at BIGINT NOT NULL
);
CREATE TABLE appeal_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_id BIGINT NOT NULL REFERENCES appeal_threads(id) ON DELETE CASCADE,
    message_id BIGINT REFERENCES appeal_messages(id) ON DELETE CASCADE,
    event_id BIGINT REFERENCES appeal_events(id) ON DELETE CASCADE,
    payload_json TEXT NOT NULL DEFAULT '{}',
    status TEXT NOT NULL DEFAULT 'pending',
    available_at BIGINT NOT NULL,
    created_at BIGINT NOT NULL,
    completed_at BIGINT,
    attempts BIGINT NOT NULL DEFAULT 0,
    lease_owner TEXT,
    lease_token TEXT,
    lease_until BIGINT,
    last_error TEXT,
    delivery_started INTEGER NOT NULL DEFAULT 0,
    discord_message_id BIGINT
);
