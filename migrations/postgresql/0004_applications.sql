CREATE TABLE application_forms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id BIGINT NOT NULL,
    config_json TEXT NOT NULL,
    enabled INTEGER NOT NULL DEFAULT 0 CHECK(enabled IN (0,1)),
    revision INTEGER NOT NULL DEFAULT 1,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);
CREATE INDEX application_forms_guild ON application_forms(guild_id,id);
CREATE TABLE applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id BIGINT NOT NULL,
    form_id BIGINT NOT NULL REFERENCES application_forms(id),
    author_id BIGINT NOT NULL,
    interaction_id BIGINT NOT NULL UNIQUE,
    snapshot_json TEXT NOT NULL,
    answers_json TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','reviewing','approved','rejected','withdrawn')),
    revision INTEGER NOT NULL DEFAULT 1,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX applications_one_open ON applications(form_id,author_id) WHERE status IN ('pending','reviewing');
CREATE INDEX applications_guild ON applications(guild_id,id);
CREATE INDEX applications_expiry ON applications(expires_at);
CREATE TABLE application_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
    actor_id BIGINT NOT NULL,
    event_type TEXT NOT NULL,
    reason TEXT NOT NULL DEFAULT '',
    created_at BIGINT NOT NULL
);
CREATE TABLE application_form_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_id BIGINT NOT NULL REFERENCES application_forms(id),
    actor_id BIGINT NOT NULL,
    revision INTEGER NOT NULL,
    created_at BIGINT NOT NULL
);
