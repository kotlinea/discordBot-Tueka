CREATE TABLE scheduled_posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    request_key TEXT NOT NULL,
    payload_json TEXT NOT NULL,
    next_due BIGINT NOT NULL,
    interval_seconds BIGINT NOT NULL,
    remaining INTEGER NOT NULL,
    status TEXT NOT NULL DEFAULT 'scheduled' CHECK(status IN ('scheduled','completed','cancelled')),
    revision INTEGER NOT NULL DEFAULT 1,
    retention_days INTEGER NOT NULL,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL,
    UNIQUE(guild_id,request_key)
);
CREATE INDEX scheduled_posts_due ON scheduled_posts(status,next_due);
CREATE INDEX scheduled_posts_guild ON scheduled_posts(guild_id,id);
CREATE TABLE scheduled_post_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES scheduled_posts(id) ON DELETE CASCADE,
    actor_id BIGINT NOT NULL,
    event_type TEXT NOT NULL,
    detail TEXT NOT NULL DEFAULT '',
    created_at BIGINT NOT NULL
);
CREATE TABLE scheduled_post_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES scheduled_posts(id) ON DELETE CASCADE,
    guild_id BIGINT NOT NULL,
    due_at BIGINT NOT NULL,
    deadline BIGINT NOT NULL,
    payload_json TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    available_at BIGINT NOT NULL,
    created_at BIGINT NOT NULL,
    completed_at BIGINT,
    attempts BIGINT NOT NULL DEFAULT 0,
    lease_owner TEXT,
    lease_token TEXT,
    lease_until BIGINT,
    last_error TEXT,
    delivery_started INTEGER NOT NULL DEFAULT 0,
    discord_receipt_id BIGINT,
    UNIQUE(post_id,due_at)
);
CREATE INDEX scheduled_post_outbox_due ON scheduled_post_outbox(status,available_at);
