CREATE TABLE starboards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    request_key TEXT NOT NULL,
    config_json TEXT NOT NULL,
    revision INTEGER NOT NULL DEFAULT 1,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    UNIQUE(guild_id,request_key)
);
CREATE INDEX starboards_guild ON starboards(guild_id,id);
CREATE TABLE starboard_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id BIGINT NOT NULL REFERENCES starboards(id) ON DELETE CASCADE,
    guild_id BIGINT NOT NULL,
    source_channel_id BIGINT NOT NULL,
    source_message_id BIGINT NOT NULL,
    snapshot_json TEXT NOT NULL,
    score INTEGER NOT NULL DEFAULT 0,
    desired INTEGER NOT NULL DEFAULT 0,
    revision INTEGER NOT NULL DEFAULT 1,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL,
    UNIQUE(board_id,source_message_id)
);
CREATE INDEX starboard_entries_source ON starboard_entries(guild_id,source_message_id);
CREATE INDEX starboard_entries_expiry ON starboard_entries(expires_at);
CREATE TABLE starboard_publications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id BIGINT NOT NULL REFERENCES starboard_entries(id) ON DELETE CASCADE,
    target_channel_id BIGINT NOT NULL,
    message_id BIGINT,
    delivery_started INTEGER NOT NULL DEFAULT 0,
    removed INTEGER NOT NULL DEFAULT 0,
    created_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX starboard_publications_active ON starboard_publications(entry_id,target_channel_id) WHERE removed=0;
CREATE TABLE starboard_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id BIGINT NOT NULL REFERENCES starboards(id) ON DELETE CASCADE,
    entry_id BIGINT REFERENCES starboard_entries(id) ON DELETE CASCADE,
    actor_id BIGINT NOT NULL,
    event_type TEXT NOT NULL,
    detail_json TEXT NOT NULL DEFAULT '{}',
    created_at BIGINT NOT NULL
);
CREATE TABLE starboard_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id BIGINT NOT NULL REFERENCES starboard_entries(id) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'pending',
    available_at BIGINT NOT NULL,
    created_at BIGINT NOT NULL,
    completed_at BIGINT,
    attempts BIGINT NOT NULL DEFAULT 0,
    lease_owner TEXT,
    lease_token TEXT,
    lease_until BIGINT,
    last_error TEXT
);
CREATE INDEX starboard_outbox_due ON starboard_outbox(status,available_at);
CREATE TABLE starboard_refresh_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id BIGINT NOT NULL,
    channel_id BIGINT NOT NULL,
    message_id BIGINT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    available_at BIGINT NOT NULL,
    created_at BIGINT NOT NULL,
    completed_at BIGINT,
    attempts BIGINT NOT NULL DEFAULT 0,
    lease_owner TEXT,
    lease_token TEXT,
    lease_until BIGINT,
    last_error TEXT,
    retry_actor_id BIGINT,
    retry_at BIGINT
);
CREATE INDEX starboard_refresh_due ON starboard_refresh_jobs(status,available_at);
CREATE INDEX starboard_refresh_source ON starboard_refresh_jobs(guild_id,channel_id,message_id,status);
