CREATE TABLE giveaways (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    request_key TEXT NOT NULL,
    config_json TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','open','closing','closed','cancelled')),
    revision INTEGER NOT NULL DEFAULT 1,
    message_id BIGINT,
    delivery_started INTEGER NOT NULL DEFAULT 0,
    round_number INTEGER NOT NULL DEFAULT 0,
    ends_at BIGINT NOT NULL,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL,
    UNIQUE(guild_id,request_key)
);
CREATE INDEX giveaways_guild ON giveaways(guild_id,id);
CREATE TABLE giveaway_entries (
    campaign_id BIGINT NOT NULL REFERENCES giveaways(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL,
    active INTEGER NOT NULL CHECK(active IN (0,1)),
    joined_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    PRIMARY KEY(campaign_id,user_id)
);
CREATE TABLE giveaway_interactions (
    interaction_id BIGINT PRIMARY KEY,
    campaign_id BIGINT NOT NULL REFERENCES giveaways(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL,
    action TEXT NOT NULL CHECK(action IN ('join','leave')),
    created_at BIGINT NOT NULL
);
CREATE TABLE giveaway_draws (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id BIGINT NOT NULL REFERENCES giveaways(id) ON DELETE CASCADE,
    round_number INTEGER NOT NULL,
    actor_id BIGINT NOT NULL,
    reason TEXT NOT NULL,
    candidates_json TEXT NOT NULL,
    winners_json TEXT NOT NULL,
    excluded_count INTEGER NOT NULL,
    candidate_hash TEXT NOT NULL,
    created_at BIGINT NOT NULL,
    UNIQUE(campaign_id,round_number)
);
CREATE TABLE giveaway_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id BIGINT NOT NULL REFERENCES giveaways(id) ON DELETE CASCADE,
    actor_id BIGINT NOT NULL,
    event_type TEXT NOT NULL,
    detail_json TEXT NOT NULL,
    created_at BIGINT NOT NULL
);
CREATE TABLE giveaway_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id BIGINT NOT NULL REFERENCES giveaways(id) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'pending',
    attempts INTEGER NOT NULL DEFAULT 0,
    available_at BIGINT NOT NULL,
    created_at BIGINT NOT NULL,
    completed_at BIGINT,
    last_error TEXT,
    lease_owner TEXT,
    lease_token TEXT,
    lease_until BIGINT
);
CREATE INDEX giveaway_outbox_due ON giveaway_outbox(status,available_at);
CREATE TABLE giveaway_draw_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id BIGINT NOT NULL REFERENCES giveaways(id) ON DELETE CASCADE,
    round_number INTEGER NOT NULL,
    actor_id BIGINT NOT NULL,
    reason TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    attempts INTEGER NOT NULL DEFAULT 0,
    available_at BIGINT NOT NULL,
    created_at BIGINT NOT NULL,
    completed_at BIGINT,
    last_error TEXT,
    lease_owner TEXT,
    lease_token TEXT,
    lease_until BIGINT,
    UNIQUE(campaign_id,round_number)
);
CREATE INDEX giveaway_draw_jobs_due ON giveaway_draw_jobs(status,available_at);
